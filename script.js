const nav = document.querySelector("nav");
const navToggle = document.querySelector(".nav-toggle");
const themeToggle = document.querySelector(".theme-toggle");
const langButtons = document.querySelectorAll(".lang-btn");

if (nav && navToggle) {
  navToggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("is-open");
    navToggle.classList.toggle("is-open", isOpen);
    navToggle.setAttribute("aria-expanded", String(isOpen));
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      nav.classList.remove("is-open");
      navToggle.classList.remove("is-open");
      navToggle.setAttribute("aria-expanded", "false");
    });
  });
}

const applyTheme = (theme) => {
  document.body.setAttribute("data-theme", theme);
  if (themeToggle) {
    themeToggle.classList.toggle("is-dark", theme === "dark");
    themeToggle.setAttribute("aria-pressed", String(theme === "dark"));
  }
  if (typeof localStorage !== "undefined") {
    localStorage.setItem("nuurTheme", theme);
  }
};

const initialTheme = (() => {
  try {
    const savedTheme = localStorage.getItem("nuurTheme");
    if (savedTheme === "dark" || savedTheme === "light") return savedTheme;
  } catch (error) {}
  return "light";
})();

applyTheme(initialTheme);

if (themeToggle) {
  themeToggle.addEventListener("click", () => {
    const nextTheme = document.body.getAttribute("data-theme") === "dark" ? "light" : "dark";
    applyTheme(nextTheme);
  });
}

const applyLanguage = (lang) => {
  const current = translations[lang] || translations.fr;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = current[key];
    if (!value) return;
    element.innerHTML = value;
  });

  langButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === lang);
  });

  if (typeof localStorage !== "undefined") {
    localStorage.setItem("nuurLang", lang);
  }
};

const initialLang = (() => {
  try {
    const savedLang = localStorage.getItem("nuurLang");
    if (savedLang && translations[savedLang]) return savedLang;
  } catch (error) {}
  return "fr";
})();

applyLanguage(initialLang);

langButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

const revealItems = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.18 });

  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("visible"));
}

